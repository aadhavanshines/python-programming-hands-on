a = 17
b = 5

print("a + b  =", a + b)
print("a - b  =", a - b)
print("a * b  =", a * b)
print("a / b  =", a / b)  # true division: always a float
print("a // b =", a // b)  # floor division: whole part only
print("a % b  =", a % b)  # remainder
print("a ** 2 =", a**2)  # power
print("round(a / b) =", round(a / b))
